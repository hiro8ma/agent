RAG_INSTRUCTIONS = "日本国憲法の条文を読んで問いに答える。答えだけを1行で、条文の言葉を使って書く。複数を問われたら全部挙げる。"

CLOSED_INSTRUCTIONS = (
    "日本国憲法についての問いに答える。答えだけを1行で書く。複数を問われたら全部挙げる。"
)


def react_user(question: str) -> str:
    return f"{REACT_INSTRUCTIONS}\n問い: {question}"


def react_prefix(transcript: str, step: int) -> str:
    return f"{transcript}思考 {step}:"


def rag_user(question: str, docs: list[Article]) -> str:
    lines = [f"文書{i}: {a.one_line()}" for i, a in enumerate(docs, 1)]
    body = "\n".join(lines) if lines else "文書なし"
    return f"{RAG_INSTRUCTIONS}\n\n{body}\n\n問い: {question}"


def closed_user(question: str) -> str:
    return f"{CLOSED_INSTRUCTIONS}\n\n問い: {question}"
